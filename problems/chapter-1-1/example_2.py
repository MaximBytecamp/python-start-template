# Известны показания счётчика в прошлом и в этом месяце и тариф — цена одного киловатт-часа.
# Посчитайте расход за месяц и сумму к оплате.

# Исходные данные
previous = 12450   # показание в прошлом месяце, кВт·ч
current = 12630    # показание в этом месяце, кВт·ч
tariff = 6.5       # цена 1 кВт·ч, руб.

# Расчёт
used = current - previous
cost = used * tariff

# Вывод
print("Расход:", used, "кВт·ч")
print("К оплате:", cost, "руб.")
