# В магазине купили несколько одинаковых тетрадей. Известны цена одной тетради и их количество.
# Выведите количество и сумму к оплате.

# Исходные данные
price = 45   # цена одной тетради, руб.
count = 3    # сколько тетрадей купили

# Расчёт
total = price * count

# Вывод
print("Тетрадей:", count)
print("К оплате:", total, "руб.")
