# Утром на складе лежит некоторое количество коробок. За день пришла поставка на 120 коробок,
# продали 75, а вечером половину остатка передали в другой магазин. Выведите остаток после каждой
# операции.

# Исходные данные
stock = 200   # коробок на складе утром

# Операции за день
stock += 120   # пришла поставка
print("После поставки:", stock)

stock -= 75    # продали
print("После продаж:", stock)

stock /= 2     # половину передали в другой магазин
print("Вечером осталось:", stock)
