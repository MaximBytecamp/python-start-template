# Программа проверяет остатки на трёх счетах и должна вывести «True», если хотя бы один остаток
# отрицательный. Программа запускается без ошибок, но в первых двух примерах выводит число 500
# вместо «True» и «False». Исправьте условие.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     500
#     -20
#     300
#   в терминале:
#     Остаток на счёте 1: 500
#     Остаток на счёте 2: -20
#     Остаток на счёте 3: 300
#     True
# Пример 2
#   ввод:
#     500
#     20
#     300
#   в терминале:
#     Остаток на счёте 1: 500
#     Остаток на счёте 2: 20
#     Остаток на счёте 3: 300
#     False
# Пример 3
#   ввод:
#     0
#     0
#     -1
#   в терминале:
#     Остаток на счёте 1: 0
#     Остаток на счёте 2: 0
#     Остаток на счёте 3: -1
#     True

# Решение: исправьте программу ниже
a = int(input("Остаток на счёте 1: "))
b = int(input("Остаток на счёте 2: "))
c = int(input("Остаток на счёте 3: "))
print(a or b or c < 0)
