# Программа оценивает пароль по длине: от 12 символов — «Надёжный пароль», от 8 до 11 —
# «Средний пароль», короче 8 — «Слабый пароль». Вводится пароль. Программа в файле запускается без
# ошибок, но на части примеров выводит две строки вместо одной. Исправьте её, чтобы вывод совпал
# со всеми примерами.
#
# Каждый input() выводит подсказку. Тексты подсказок — как в примерах, после двоеточия или скобки
# стоит пробел.
#
# Пример 1
#   ввод:
#     correct_horse_7
#   в терминале:
#     Пароль: correct_horse_7
#     Надёжный пароль
# Пример 2
#   ввод:
#     sunrise7a
#   в терминале:
#     Пароль: sunrise7a
#     Средний пароль
# Пример 3
#   ввод:
#     qwe12
#   в терминале:
#     Пароль: qwe12
#     Слабый пароль
# Пример 4
#   ввод:
#     abcdefgh
#   в терминале:
#     Пароль: abcdefgh
#     Средний пароль

# Решение: исправьте программу ниже
password = input("Пароль: ")
length = len(password)
if length >= 8:
    print("Средний пароль")
if length >= 12:
    print("Надёжный пароль")
else:
    print("Слабый пароль")
