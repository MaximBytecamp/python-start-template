# Программа оценивает пароль по длине: от 12 символов — «Надёжный пароль», от 8 до 11 —
# «Средний пароль», короче 8 — «Слабый пароль». Вводится пароль. Программа в файле запускается без
# ошибок, но на части примеров выводит две строки вместо одной. Исправьте её, чтобы вывод совпал
# со всеми примерами.
#
# Пример 1
#   ввод:
#     correct_horse_7
#   вывод:
#     Надёжный пароль
# Пример 2
#   ввод:
#     sunrise7a
#   вывод:
#     Средний пароль
# Пример 3
#   ввод:
#     qwe12
#   вывод:
#     Слабый пароль
# Пример 4
#   ввод:
#     abcdefgh
#   вывод:
#     Средний пароль

# Решение: исправьте программу ниже
password = input()
length = len(password)
if length >= 8:
    print("Средний пароль")
if length >= 12:
    print("Надёжный пароль")
else:
    print("Слабый пароль")
